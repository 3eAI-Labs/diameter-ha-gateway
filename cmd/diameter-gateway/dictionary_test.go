// TestDictionary_RequestAVPs: the gateway answers a request carrying an AVP
// it does not know, with the M bit, 5001 (RFC 6733 §4.1); every AVP its
// requests may carry must therefore be in the dictionary of their
// application.
func TestDictionary_RequestAVPs(t *testing.T) {
	for _, r := range requestAVPs {
		_, err := dict.Default.FindAVPWithVendor(r.app, r.code, r.vendor)
		assert.NoError(t, err, "%s in %s: %d/%d", r.name, r.command, r.code, r.vendor)
	}
}
